fn py_str(value: &str) -> PyExpr {
    PyExpr::atom(python_string_literal(value))
}

fn py_bool(value: bool) -> PyExpr {
    PyExpr::atom(if value { "True" } else { "False" })
}

fn py_f32(value: f32) -> PyExpr {
    PyExpr::atom(format!("{value:?}"))
}

fn py_f64(value: f64) -> PyExpr {
    PyExpr::atom(format!("{value:?}"))
}

fn py_color(color: Color) -> PyExpr {
    if let Some(name) = name_from_color(&color) {
        return py_str(name);
    }
    let (r, g, b, a) = color_to_ints(&color);
    PyExpr::call("color")
        .arg(PyExpr::atom(r.to_string()))
        .arg(PyExpr::atom(g.to_string()))
        .arg(PyExpr::atom(b.to_string()))
        .arg(PyExpr::atom(a.to_string()))
}

fn py_vec3_f32((x, y, z): (f32, f32, f32)) -> PyExpr {
    PyExpr::atom(format!("({x:?}, {y:?}, {z:?})"))
}

fn py_vec3_f64((x, y, z): (f64, f64, f64)) -> PyExpr {
    PyExpr::atom(format!("({x:?}, {y:?}, {z:?})"))
}

fn py_quat([x, y, z, w]: [f64; 4]) -> PyExpr {
    PyExpr::atom(format!("({x:?}, {y:?}, {z:?}, {w:?})"))
}

fn python_string_literal(value: &str) -> String {
    let mut out = String::from("\"");
    for ch in value.chars() {
        match ch {
            '\\' => out.push_str("\\\\"),
            '"' => out.push_str("\\\""),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\t' => out.push_str("\\t"),
            c if c.is_control() => {
                use std::fmt::Write;
                write!(out, "\\u{:04x}", c as u32).expect("writing to String cannot fail");
            }
            c => out.push(c),
        }
    }
    out.push('"');
    out
}

