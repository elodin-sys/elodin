/// Convert a KDL schematic into an executable typed `elodin.ui` module.
pub fn schematic_to_python(
    source: &str,
    source_name: Option<&str>,
) -> Result<String, KdlSchematicError> {
    let schematic = parse_schematic(source)?;

    let source_name = source_name.unwrap_or("schematic.kdl");
    let mut out = String::new();
    out.push_str("\"\"\"Generated by `elodin schematic to-python`.\n\n");
    out.push_str("Typed elodin.ui translation of ");
    out.push_str(source_name);
    out.push_str(".\n");
    out.push_str("\"\"\"\n\n");

    for line in source.lines() {
        let comment = line.trim_start();
        if let Some(comment) = comment.strip_prefix("//") {
            out.push('#');
            out.push_str(comment);
            out.push('\n');
        }
    }
    if source
        .lines()
        .any(|line| line.trim_start().starts_with("//"))
    {
        out.push('\n');
    }

    out.push_str("import elodin.ui as ui\n\n");
    out.push_str("def build() -> ui.Schematic:\n");
    out.push_str("    return ");
    out.push_str(&schematic_expr(&schematic).render(1));
    out.push_str("\n\n\n");
    out.push_str("if __name__ == \"__main__\":\n");
    out.push_str("    print(build().emit_kdl())\n");
    Ok(out)
}

#[derive(Debug)]
enum PyExpr {
    Atom(String),
    Call {
        function: &'static str,
        args: Vec<(Option<&'static str>, PyExpr)>,
    },
    List(Vec<PyExpr>),
}

impl PyExpr {
    fn atom(value: impl Into<String>) -> Self {
        Self::Atom(value.into())
    }

    fn call(function: &'static str) -> Self {
        Self::Call {
            function,
            args: Vec::new(),
        }
    }

    fn arg(mut self, value: PyExpr) -> Self {
        let Self::Call { args, .. } = &mut self else {
            unreachable!("arguments can only be added to calls");
        };
        args.push((None, value));
        self
    }

    fn kw(mut self, name: &'static str, value: PyExpr) -> Self {
        let Self::Call { args, .. } = &mut self else {
            unreachable!("arguments can only be added to calls");
        };
        args.push((Some(name), value));
        self
    }

    fn kw_opt(self, name: &'static str, value: Option<PyExpr>) -> Self {
        match value {
            Some(value) => self.kw(name, value),
            None => self,
        }
    }

    fn render(&self, indent: usize) -> String {
        match self {
            Self::Atom(value) => value.clone(),
            Self::List(items) => {
                if items.is_empty() {
                    return "[]".to_string();
                }
                let pad = "    ".repeat(indent);
                let child_pad = "    ".repeat(indent + 1);
                let mut out = String::from("[\n");
                for item in items {
                    out.push_str(&child_pad);
                    out.push_str(&item.render(indent + 1));
                    out.push_str(",\n");
                }
                out.push_str(&pad);
                out.push(']');
                out
            }
            Self::Call { function, args } => {
                if args.is_empty() {
                    return format!("ui.{function}()");
                }
                let pad = "    ".repeat(indent);
                let child_pad = "    ".repeat(indent + 1);
                let mut out = format!("ui.{function}(\n");
                for (name, value) in args {
                    out.push_str(&child_pad);
                    if let Some(name) = name {
                        out.push_str(name);
                        out.push('=');
                    }
                    out.push_str(&value.render(indent + 1));
                    out.push_str(",\n");
                }
                out.push_str(&pad);
                out.push(')');
                out
            }
        }
    }
}

fn schematic_expr(schematic: &Schematic) -> PyExpr {
    let mut call = PyExpr::call("schematic");
    for elem in &schematic.elems {
        call = call.arg(schematic_elem_expr(elem));
    }
    call = call
        .kw_opt(
            "coordinate",
            schematic.frame.map(|frame| {
                let mut coordinate =
                    PyExpr::call("coordinate").kw("frame", py_str(<&str>::from(frame)));
                if let Some(origin) = schematic.origin {
                    coordinate = coordinate
                        .kw("lat", py_f64(origin.latitude))
                        .kw("lon", py_f64(origin.longitude))
                        .kw("alt", py_f64(origin.altitude));
                }
                coordinate.kw_opt("body", schematic.body.map(|body| py_str(body.as_str())))
            }),
        )
        .kw_opt("theme", schematic.theme.as_ref().map(theme_expr))
        .kw_opt("timeline", schematic.timeline.as_ref().map(timeline_expr))
        .kw_opt(
            "skybox",
            schematic.skybox.as_ref().map(|skybox| py_str(&skybox.name)),
        )
        .kw_opt(
            "environment",
            schematic.environment.as_ref().map(environment_expr),
        );
    if schematic.telemetry_mode {
        call = call.kw("telemetry_mode", py_bool(true));
    }
    call
}

fn schematic_elem_expr(elem: &SchematicElem) -> PyExpr {
    match elem {
        SchematicElem::Panel(panel) => panel_expr(panel, None),
        SchematicElem::Object3d(object) => object_expr(object),
        SchematicElem::Line3d(line) => line_expr(line),
        SchematicElem::VectorArrow(arrow) => vector_arrow_expr(arrow),
        SchematicElem::WorldMesh(mesh) => world_mesh_expr(mesh),
        SchematicElem::Window(window) => window_expr(window),
        SchematicElem::Theme(theme) => theme_expr(theme),
        SchematicElem::Timeline(timeline) => timeline_expr(timeline),
        SchematicElem::Coordinate(coordinate) => PyExpr::call("coordinate")
            .kw("frame", py_str(<&str>::from(coordinate.frame)))
            .kw_opt(
                "lat",
                coordinate.origin.map(|origin| py_f64(origin.latitude)),
            )
            .kw_opt(
                "lon",
                coordinate.origin.map(|origin| py_f64(origin.longitude)),
            )
            .kw_opt(
                "alt",
                coordinate.origin.map(|origin| py_f64(origin.altitude)),
            )
            .kw_opt("body", coordinate.body.map(|body| py_str(body.as_str()))),
    }
}

fn panel_expr(panel: &Panel, share: Option<f32>) -> PyExpr {
    match panel {
        Panel::Tabs(panels) => {
            let mut call = PyExpr::call("tabs");
            for panel in panels {
                call = call.arg(panel_expr(panel, None));
            }
            call.kw_opt("share", share.map(py_f32))
        }
        Panel::HSplit(split) => split_expr("hsplit", split, share),
        Panel::VSplit(split) => split_expr("vsplit", split, share),
        Panel::Viewport(viewport) => viewport_expr(viewport, share),
        Panel::Graph(graph) => graph_expr(graph, share),
        Panel::ComponentMonitor(monitor) => PyExpr::call("component_monitor")
            .arg(py_str(&monitor.component_name))
            .kw_opt("name", monitor.name.as_deref().map(py_str))
            .kw_opt("share", share.map(py_f32)),
        Panel::GeoPositionGauge(gauge) => PyExpr::call("geo_position_gauge")
            .arg(py_str(&gauge.eql))
            .kw_opt("name", gauge.name.as_deref().map(py_str))
            .kw_opt(
                "source",
                gauge.source.map(|frame| py_str(<&str>::from(frame))),
            )
            .kw("display", py_str(gauge.display.as_str()))
            .kw_opt("share", share.map(py_f32)),
        Panel::OrientationGauge(gauge) => PyExpr::call("orientation_gauge")
            .arg(py_str(&gauge.eql))
            .kw_opt("name", gauge.name.as_deref().map(py_str))
            .kw_opt(
                "source",
                gauge.source.map(|frame| py_str(<&str>::from(frame))),
            )
            .kw_opt(
                "display",
                gauge.display.map(|frame| py_str(<&str>::from(frame))),
            )
            .kw_opt("reference", gauge.reference.map(py_quat))
            .kw_opt("share", share.map(py_f32)),
        Panel::HorizonGauge(gauge) => PyExpr::call("horizon_gauge")
            .arg(py_str(&gauge.eql))
            .kw_opt("name", gauge.name.as_deref().map(py_str))
            .kw_opt(
                "source",
                gauge.source.map(|frame| py_str(<&str>::from(frame))),
            )
            .kw_opt("reference", gauge.reference.map(py_quat))
            .kw_opt("share", share.map(py_f32)),
        Panel::ActionPane(action) => PyExpr::call("action_pane")
            .arg(py_str(&action.name))
            .arg(py_str(&action.lua))
            .kw_opt("share", share.map(py_f32)),
        Panel::QueryTable(table) => PyExpr::call("query_table")
            .arg(py_str(&table.query))
            .kw_opt("name", table.name.as_deref().map(py_str))
            .kw(
                "query_type",
                py_str(match table.query_type {
                    QueryType::EQL => "eql",
                    QueryType::SQL => "sql",
                }),
            )
            .kw_opt("share", share.map(py_f32)),
        Panel::QueryPlot(plot) => PyExpr::call("query_plot")
            .arg(py_str(&plot.name))
            .arg(py_str(&plot.query))
            .kw(
                "refresh_interval_ms",
                py_f64(plot.refresh_interval.as_secs_f64() * 1000.0),
            )
            .kw("auto_refresh", py_bool(plot.auto_refresh))
            .kw("color", py_color(plot.color))
            .kw(
                "query_type",
                py_str(match plot.query_type {
                    QueryType::EQL => "eql",
                    QueryType::SQL => "sql",
                }),
            )
            .kw(
                "plot_mode",
                py_str(match plot.plot_mode {
                    PlotMode::TimeSeries => "time_series",
                    PlotMode::XY => "xy",
                }),
            )
            .kw_opt("x_label", plot.x_label.as_deref().map(py_str))
            .kw_opt("y_label", plot.y_label.as_deref().map(py_str))
            .kw_opt("share", share.map(py_f32)),
        Panel::Inspector => PyExpr::call("inspector").kw_opt("share", share.map(py_f32)),
        Panel::Hierarchy => PyExpr::call("hierarchy").kw_opt("share", share.map(py_f32)),
        Panel::SchematicTree(name) => PyExpr::call("schematic_tree")
            .kw_opt("name", name.as_deref().map(py_str))
            .kw_opt("share", share.map(py_f32)),
        Panel::DataOverview(name) => PyExpr::call("data_overview")
            .kw_opt("name", name.as_deref().map(py_str))
            .kw_opt("share", share.map(py_f32)),
        Panel::VideoStream(stream) => PyExpr::call("video_stream")
            .arg(py_str(&stream.msg_name))
            .kw_opt("name", stream.name.as_deref().map(py_str))
            .kw_opt("share", share.map(py_f32)),
        Panel::SensorView(view) => PyExpr::call("sensor_view")
            .arg(py_str(&view.msg_name))
            .kw_opt("name", view.name.as_deref().map(py_str))
            .kw_opt("share", share.map(py_f32)),
        Panel::LogStream(stream) => PyExpr::call("log_stream")
            .arg(py_str(&stream.msg_name))
            .kw_opt("name", stream.name.as_deref().map(py_str))
            .kw_opt("share", share.map(py_f32)),
    }
}

fn split_expr(function: &'static str, split: &Split, share: Option<f32>) -> PyExpr {
    let mut call = PyExpr::call(function);
    for (index, panel) in split.panels.iter().enumerate() {
        call = call.arg(panel_expr(panel, split.shares.get(&index).copied()));
    }
    call = call.kw_opt("name", split.name.as_deref().map(py_str));
    if split.active {
        call = call.kw("active", py_bool(true));
    }
    call.kw_opt("share", share.map(py_f32))
}

fn graph_expr(graph: &Graph, share: Option<f32>) -> PyExpr {
    let mut call = PyExpr::call("graph")
        .arg(py_str(&graph.eql))
        .kw_opt("name", graph.name.as_deref().map(py_str));
    if graph.graph_type != GraphType::Line {
        call = call.kw(
            "graph_type",
            py_str(match graph.graph_type {
                GraphType::Line => "line",
                GraphType::Point => "point",
                GraphType::Bar => "bar",
            }),
        );
    }
    if graph.locked {
        call = call.kw("locked", py_bool(true));
    }
    if !graph.auto_y_range {
        call = call
            .kw("auto_y_range", py_bool(false))
            .kw("y_min", py_f64(graph.y_range.start))
            .kw("y_max", py_f64(graph.y_range.end));
    }
    if !graph.colors.is_empty() {
        call = call.kw(
            "colors",
            PyExpr::List(graph.colors.iter().copied().map(py_color).collect()),
        );
    }
    call.kw_opt("share", share.map(py_f32))
}

fn viewport_expr(viewport: &Viewport, share: Option<f32>) -> PyExpr {
    let mut call = PyExpr::call("viewport")
        .kw_opt("name", viewport.name.as_deref().map(py_str))
        .kw("fov", py_f32(viewport.fov))
        .kw_opt("near", viewport.near.map(py_f32))
        .kw_opt("far", viewport.far.map(py_f32))
        .kw_opt("aspect", viewport.aspect.map(py_f32))
        .kw("active", py_bool(viewport.active))
        .kw("show_grid", py_bool(viewport.show_grid))
        .kw("show_arrows", py_bool(viewport.show_arrows))
        .kw("create_frustum", py_bool(viewport.create_frustum))
        .kw("show_frustums", py_bool(viewport.show_frustums))
        .kw("frustums_color", py_color(viewport.frustums_color))
        .kw("projection_color", py_color(viewport.projection_color))
        .kw("frustums_thickness", py_f32(viewport.frustums_thickness))
        .kw("show_view_cube", py_bool(viewport.show_view_cube))
        .kw_opt(
            "view_cube_frame",
            viewport
                .view_cube_frame
                .map(|frame| py_str(<&str>::from(frame))),
        )
        .kw("effects", py_bool(viewport.effects))
        .kw("hdr", py_bool(viewport.hdr))
        .kw("cinematic", py_bool(viewport.cinematic))
        .kw_opt("bloom", viewport.bloom.as_ref().map(bloom_expr))
        .kw_opt("ev100", viewport.ev100.map(py_f32))
        .kw_opt("pos", viewport.pos.as_deref().map(py_str))
        .kw_opt("look_at", viewport.look_at.as_deref().map(py_str))
        .kw_opt("up", viewport.up.as_deref().map(py_str))
        .kw("smoothing", py_f32(viewport.smoothing))
        .kw_opt(
            "frame",
            viewport.frame.map(|frame| py_str(<&str>::from(frame))),
        );
    if !viewport.local_arrows.is_empty() {
        call = call.kw(
            "arrows",
            PyExpr::List(
                viewport
                    .local_arrows
                    .iter()
                    .map(vector_arrow_expr)
                    .collect(),
            ),
        );
    }
    call.kw_opt("share", share.map(py_f32))
}

