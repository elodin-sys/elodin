fn object_expr(object: &Object3D) -> PyExpr {
    let mut call = PyExpr::call("object_3d")
        .arg(py_str(&object.eql))
        .kw("mesh", object_mesh_expr(&object.mesh))
        .kw_opt(
            "frame",
            object.frame.map(|frame| py_str(<&str>::from(frame))),
        )
        .kw_opt(
            "frame_orientation",
            object
                .frame_orientation
                .map(|frame| py_str(<&str>::from(frame))),
        )
        .kw(
            "orientation",
            py_str(match object.orientation {
                bevy_geo_frames::RotationKind::Relative => "relative",
                bevy_geo_frames::RotationKind::Absolute => "absolute",
            }),
        )
        .kw_opt("icon", object.icon.as_ref().map(icon_expr))
        .kw_opt(
            "visibility",
            object.mesh_visibility_range.as_ref().map(vis_range_expr),
        );
    if let Object3DMesh::Glb { animations, .. } = &object.mesh
        && !animations.is_empty()
    {
        call = call.kw(
            "animate",
            PyExpr::List(
                animations
                    .iter()
                    .map(|animation| {
                        PyExpr::call("joint")
                            .arg(py_str(&animation.joint_name))
                            .arg(py_str(&animation.eql_expr))
                    })
                    .collect(),
            ),
        );
    }
    if !object.thrusters.is_empty() {
        call = call.kw(
            "thrusters",
            PyExpr::List(object.thrusters.iter().map(thruster_expr).collect()),
        );
    }
    call
}

fn object_mesh_expr(mesh: &Object3DMesh) -> PyExpr {
    match mesh {
        Object3DMesh::Glb {
            path,
            scale,
            translate,
            rotate,
            animations: _,
            emissivity,
            glow,
            glow_color,
        } => PyExpr::call("glb")
            .arg(py_str(path))
            .kw("scale", py_f32(*scale))
            .kw("translate", py_vec3_f32(*translate))
            .kw("rotate", py_vec3_f32(*rotate))
            .kw("emissivity", py_f32(*emissivity))
            .kw("glow", py_f32(*glow))
            .kw_opt("glow_color", glow_color.map(py_color)),
        Object3DMesh::Mesh { mesh, material } => match mesh {
            Mesh::Sphere { radius } => PyExpr::call("sphere")
                .kw("radius", py_f32(*radius))
                .kw("color", py_color(material.base_color))
                .kw("emissivity", py_f32(material.emissivity)),
            Mesh::Box { x, y, z } => PyExpr::call("box")
                .kw("x", py_f32(*x))
                .kw("y", py_f32(*y))
                .kw("z", py_f32(*z))
                .kw("color", py_color(material.base_color))
                .kw("emissivity", py_f32(material.emissivity)),
            Mesh::Cylinder { radius, height } => PyExpr::call("cylinder")
                .kw("radius", py_f32(*radius))
                .kw("height", py_f32(*height))
                .kw("color", py_color(material.base_color))
                .kw("emissivity", py_f32(material.emissivity)),
            Mesh::Plane { width, depth } => PyExpr::call("plane")
                .kw("width", py_f32(*width))
                .kw("depth", py_f32(*depth))
                .kw("color", py_color(material.base_color))
                .kw("emissivity", py_f32(material.emissivity)),
        },
        Object3DMesh::Ellipsoid {
            scale,
            color,
            error_covariance_cholesky,
            error_covariance,
            error_confidence_interval,
            show_grid,
            grid_color,
        } => PyExpr::call("ellipsoid")
            .kw("scale", py_str(scale))
            .kw("color", py_color(*color))
            .kw_opt(
                "error_covariance_cholesky",
                error_covariance_cholesky.as_deref().map(py_str),
            )
            .kw_opt("error_covariance", error_covariance.as_deref().map(py_str))
            .kw(
                "error_confidence_interval",
                py_f32(*error_confidence_interval),
            )
            .kw("show_grid", py_bool(*show_grid))
            .kw("grid_color", py_color(*grid_color)),
    }
}

fn icon_expr(icon: &Object3DIcon) -> PyExpr {
    let call = match &icon.source {
        Object3DIconSource::Path(path) => PyExpr::call("icon").kw("path", py_str(path)),
        Object3DIconSource::Builtin(name) => PyExpr::call("icon").kw("builtin", py_str(name)),
    };
    call.kw("color", py_color(icon.color))
        .kw("size", py_f32(icon.size))
        .kw_opt(
            "visibility",
            icon.visibility_range.as_ref().map(vis_range_expr),
        )
}

fn vis_range_expr(range: &VisRange) -> PyExpr {
    PyExpr::call("visibility_range")
        .kw("min", py_f32(range.min))
        .kw("max", py_f32(range.max))
        .kw("fade_distance", py_f32(range.fade_distance))
}

fn thruster_expr(thruster: &Thruster) -> PyExpr {
    let mut call = PyExpr::call("thruster")
        .kw_opt("name", thruster.name.as_deref().map(py_str))
        .kw("body_frame", py_bool(thruster.body_frame))
        .kw("position", py_vec3_f32(thruster.position))
        .kw_opt("direction", thruster.direction.map(py_vec3_f32))
        .kw("intensity", py_str(&thruster.intensity))
        .kw("effect", py_str(&thruster.effect))
        .kw_opt("emission_rate", thruster.emission_rate.map(py_f32))
        .kw("cutoff", py_f32(thruster.cutoff))
        .kw("scale", py_f32(thruster.scale))
        .kw_opt("light", thruster.light.as_ref().map(thruster_light_expr));
    if !thruster.extra_effects.is_empty() {
        call = call.kw(
            "extra_effects",
            PyExpr::List(
                thruster
                    .extra_effects
                    .iter()
                    .map(|effect| py_str(effect))
                    .collect(),
            ),
        );
    }
    call
}

