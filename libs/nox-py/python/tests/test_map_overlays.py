import pytest
from elodin import ui


def test_map_overlays_roundtrip_through_python_and_kdl():
    scene = ui.schematic(
        ui.viewport(),
        map_overlays=[
            ui.map_overlay("overlays/cape-canaveral.json"),
            ui.map_overlay("db:overlays/orbital-context.json", visible=False),
        ],
    )
    assert ui.from_kdl(scene.emit_kdl()) == scene
    generated = ui.to_python(scene.emit_kdl())
    namespace = {}
    exec(generated, namespace)  # noqa: S102 - execute code generated by the local serializer
    assert namespace["build"]() == scene


@pytest.mark.parametrize("path", ["../x.json", "https://example.com/x.json", "x.glb"])
def test_map_overlay_requires_portable_json_asset(path):
    with pytest.raises(ValueError):
        ui.map_overlay(path)
